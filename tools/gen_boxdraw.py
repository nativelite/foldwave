#!/usr/bin/env python3
"""Generate crates/fwrender/src/boxdraw_table.rs: the arms of every box-drawing
character (U+2500..U+257F), read from the Unicode character names.

Each name spells out its lines: "BOX DRAWINGS DOWN LIGHT AND RIGHT HEAVY",
"BOX DRAWINGS DOUBLE VERTICAL AND LEFT", "BOX DRAWINGS LIGHT UP AND HEAVY DOWN".
Groups are separated by AND; a group's directions (UP, DOWN, LEFT, RIGHT,
VERTICAL, HORIZONTAL) take the weight named in it (LIGHT or SINGLE, HEAVY,
DOUBLE), or the previous group's. Dashed lines, arcs and diagonals are named
too and marked so the drawing code treats them. Stdlib only.

    python tools/gen_boxdraw.py        # rewrite the table
    python tools/gen_boxdraw.py --check  # fail if it is out of date
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "crates/fwrender/src/boxdraw_table.rs"
WEIGHT = {"LIGHT": 1, "SINGLE": 1, "HEAVY": 2, "DOUBLE": 3}
DIRS = {
    "UP": ["up"],
    "DOWN": ["down"],
    "LEFT": ["left"],
    "RIGHT": ["right"],
    "VERTICAL": ["up", "down"],
    "HORIZONTAL": ["left", "right"],
}
ORDER = ["up", "right", "down", "left"]


def arms(name: str) -> tuple[list[int], int, str]:
    """(weights up/right/down/left, dashes, kind) for one character name."""
    rest = name.removeprefix("BOX DRAWINGS ")
    kind, dashes = "lines", 0
    for word, n in (("DOUBLE DASH", 2), ("TRIPLE DASH", 3), ("QUADRUPLE DASH", 4)):
        if word in rest:
            dashes = n
            rest = rest.replace(word + " ", "")
    if " ARC " in f" {rest} ":
        kind = "arc"
        rest = rest.replace("ARC ", "")
    if "DIAGONAL" in rest:
        kind = "diagonal"
    out = {d: 0 for d in ORDER}
    weight = 0
    for group in rest.split(" AND "):
        words = group.split()
        w = next((WEIGHT[x] for x in words if x in WEIGHT), None)
        weight = w if w is not None else weight
        for x in words:
            for d in DIRS.get(x, []):
                out[d] = weight
    return [out[d] for d in ORDER], dashes, kind


def table() -> str:
    lines = [
        "//! Generated by tools/gen_boxdraw.py from the Unicode character names;",
        "//! do not edit. Box-drawing characters U+2500..=U+257F: the weight of",
        "//! each arm (up, right, down, left: 0 none, 1 light, 2 heavy, 3 double),",
        "//! how many dashes a dashed line has (0: solid), and its kind.",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub(crate) enum Kind {",
        "    Lines,",
        "    Arc,",
        "    Diagonal,",
        "}",
        "",
        "#[rustfmt::skip]",
        "pub(crate) const BOX: [([u8; 4], u8, Kind); 128] = [",
    ]
    for cp in range(0x2500, 0x2580):
        name = unicodedata.name(chr(cp))
        a, dashes, kind = arms(name)
        k = {"lines": "Kind::Lines", "arc": "Kind::Arc", "diagonal": "Kind::Diagonal"}[kind]
        lines.append(f"    ({a}, {dashes}, {k}), // U+{cp:04X} {name.removeprefix('BOX DRAWINGS ').lower()}")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = table()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{OUT} is out of date: run python tools/gen_boxdraw.py")
            return 1
        print(f"{OUT} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
