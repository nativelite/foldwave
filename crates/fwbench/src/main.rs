#[derive(Debug, PartialEq)]
enum Mode {
    Flood,
    Echo,
    Combined,
    Disk,
    Parse,
    Gpu,
    Read,
    Compose,
    Replay,
    CrashWriter,
    History,
    Render,
    Glyphs,
    Emit { bytes: u64 },
}

#[derive(Debug)]
struct Args {
    mode: Mode,
    panes: usize,
    mib: u64,
    samples: usize,
    gap: Duration,
    shell: Option<String>,
    attribution: bool,
    transport: Transport,
    path: Option<String>,
    io_kib: usize,
    qd: usize,
    threads: Vec<usize>,
    reps: usize,
    noise_limit: f64,
    conpty: Option<String>,
    emit_cached: bool,
    emit_raw: bool,
    echo: bool,
    checkpoint_mib: u64,
    kill_ms: u64,
    visible: usize,
    log: compose::LogMode,
    rate_mib: f64,
    flush_mib: u64,
    flush_path: Option<String>,
    render: RenderArgs,
}

/// `render` mode's options.
#[derive(Debug, Clone, PartialEq)]
struct RenderArgs {
    backend: String,
    seconds: u64,
    present: String,
    font: String,
    px: i32,
    size: (u32, u32),
    max_fps: u32,
    gdi: bool,
}

impl Default for RenderArgs {
    fn default() -> Self {
        RenderArgs {
            backend: "cpu".into(),
            seconds: 10,
            present: "fifo".into(),
            font: "Consolas".into(),
            px: 16,
            size: (1600, 900),
            max_fps: 0,
            gdi: false,
        }
    }
}

fn parse(argv: &[String]) -> Result<Args, String> {
    let mut mode: Option<Mode> = None;
    let mut panes = 8usize;
    let mut mib: Option<u64> = None;
    let mut samples = 200usize;
    let mut gap_ms = 25u64;
    let mut shell = None;
    let mut attribution = true;
    let mut transport = Transport::Pty;
    let mut path = None;
    let mut io_kib = 1024usize;
    let mut qd = 8usize;
    let mut threads = vec![1, 2, 4, 6, 8, 12, 16];
    let mut reps = 5usize;
    let mut noise_limit = noise::DEFAULT_LIMIT_CORES;
    let mut conpty: Option<String> = None;
    let mut emit_cached = false;
    let mut emit_raw = false;
    let mut echo = false;
    let mut checkpoint_mib = 0u64;
    let mut kill_ms = 1500u64;
    let mut visible = 4usize;
    let mut log = compose::LogMode::PerPane;
    let mut rate_mib = 0.0f64;
    let mut flush_mib = 0u64;
    let mut flush_path: Option<String> = None;
    let mut emit_bytes: Option<u64> = None;
    let mut render = RenderArgs::default();

    let mut i = 0;
    let value = |i: &mut usize, flag: &str| -> Result<String, String> {
        let v = argv
            .get(*i + 1)
            .ok_or_else(|| format!("{flag} needs a value"))?
            .clone();
        *i += 2;
        Ok(v)
    };

    while i < argv.len() {
        match argv[i].as_str() {
            "-h" | "--help" => return Err(USAGE.to_string()),
            "flood" => {
                mode = Some(Mode::Flood);
                i += 1;
            }
            "echo" => {
                mode = Some(Mode::Echo);
                i += 1;
            }
            "combined" => {
                mode = Some(Mode::Combined);
                i += 1;
            }
            "disk" => {
                mode = Some(Mode::Disk);
                i += 1;
            }
            "history" => {
                mode = Some(Mode::History);
                i += 1;
            }
            "replay" => {
                mode = Some(Mode::Replay);
                i += 1;
            }
            "render" => {
                mode = Some(Mode::Render);
                i += 1;
            }
            "glyphs" => {
                mode = Some(Mode::Glyphs);
                i += 1;
            }
            "--backend" => {
                let v = value(&mut i, "--backend")?;
                if v != "cpu" && v != "vulkan" {
                    return Err(format!("bad --backend {v:?}, want cpu or vulkan"));
                }
                render.backend = v;
            }
            "--seconds" => {
                let v = value(&mut i, "--seconds")?;
                render.seconds = v.parse().map_err(|_| format!("bad --seconds {v:?}"))?;
            }
            "--present" => {
                let v = value(&mut i, "--present")?;
                if !matches!(v.as_str(), "fifo" | "mailbox" | "immediate") {
                    return Err(format!(
                        "bad --present {v:?}, want fifo, mailbox or immediate"
                    ));
                }
                render.present = v;
            }
            "--font" => render.font = value(&mut i, "--font")?,
            "--gdi" => {
                render.gdi = true;
                i += 1;
            }
            "--max-fps" => {
                let v = value(&mut i, "--max-fps")?;
                render.max_fps = v.parse().map_err(|_| format!("bad --max-fps {v:?}"))?;
            }
            "--px" => {
                let v = value(&mut i, "--px")?;
                render.px = match v.parse() {
                    Ok(n) if n > 0 => n,
                    _ => return Err(format!("bad --px {v:?}")),
                };
            }
            "--size" => {
                let v = value(&mut i, "--size")?;
                let wh = v
                    .split_once('x')
                    .and_then(|(w, h)| Some((w.parse().ok()?, h.parse().ok()?)))
                    .filter(|&(w, h): &(u32, u32)| w >= 64 && h >= 64);
                render.size = wh.ok_or_else(|| format!("bad --size {v:?}, want WxH"))?;
            }
            "--crash-writer" => {
                mode = Some(Mode::CrashWriter);
                i += 1;
            }
            "--conpty" => conpty = Some(value(&mut i, "--conpty")?),
            // `--cached` / `--raw` are the child's spelling; the flood modes
            // take `--emit-cached` / `--emit-raw` and pass them on.
            "--cached" | "--emit-cached" => {
                emit_cached = true;
                i += 1;
            }
            "--raw" | "--emit-raw" => {
                emit_raw = true;
                i += 1;
            }
            "--echo" => {
                echo = true;
                i += 1;
            }
            "--checkpoint-mib" => {
                let v = value(&mut i, "--checkpoint-mib")?;
                checkpoint_mib = v
                    .parse()
                    .map_err(|_| format!("bad --checkpoint-mib {v:?}"))?;
            }
            "--kill-ms" => {
                let v = value(&mut i, "--kill-ms")?;
                kill_ms = v.parse().map_err(|_| format!("bad --kill-ms {v:?}"))?;
            }
            "compose" => {
                mode = Some(Mode::Compose);
                i += 1;
            }
            "--visible" => {
                let v = value(&mut i, "--visible")?;
                visible = v.parse().map_err(|_| format!("bad --visible {v:?}"))?;
            }
            "--log" => {
                let v = value(&mut i, "--log")?;
                log = compose::LogMode::parse(&v)
                    .ok_or_else(|| format!("bad --log {v:?}, want per-pane, single or none"))?;
            }
            "--rate" => {
                let v = value(&mut i, "--rate")?;
                rate_mib = v.parse().map_err(|_| format!("bad --rate {v:?}"))?;
                if !(rate_mib >= 0.0 && rate_mib.is_finite()) {
                    return Err("--rate must be a non-negative number of MiB/s".into());
                }
            }
            "read" => {
                mode = Some(Mode::Read);
                i += 1;
            }
            "gpu" => {
                mode = Some(Mode::Gpu);
                i += 1;
            }
            "parse" => {
                mode = Some(Mode::Parse);
                i += 1;
            }
            "--threads" => {
                let v = value(&mut i, "--threads")?;
                threads = if v == "none" {
                    Vec::new()
                } else {
                    v.split(',')
                        .map(|t| match t.trim().parse::<usize>() {
                            Ok(n) if n > 0 => Ok(n),
                            _ => Err(format!("bad --threads {v:?}")),
                        })
                        .collect::<Result<_, _>>()?
                };
            }
            "--reps" => {
                let v = value(&mut i, "--reps")?;
                reps = v.parse().map_err(|_| format!("bad --reps {v:?}"))?;
                if reps == 0 {
                    return Err("--reps must be at least 1".into());
                }
            }
            "--noise-limit" => {
                let v = value(&mut i, "--noise-limit")?;
                noise_limit = v.parse().map_err(|_| format!("bad --noise-limit {v:?}"))?;
                if !(noise_limit >= 0.0 && noise_limit.is_finite()) {
                    return Err("--noise-limit must be a non-negative number of cores".into());
                }
            }
            "--path" => path = Some(value(&mut i, "--path")?),
            "--flush-mib" => {
                let v = value(&mut i, "--flush-mib")?;
                flush_mib = v.parse().map_err(|_| format!("bad --flush-mib {v:?}"))?;
            }
            "--flush-path" => flush_path = Some(value(&mut i, "--flush-path")?),
            "--io-kib" => {
                let v = value(&mut i, "--io-kib")?;
                io_kib = v.parse().map_err(|_| format!("bad --io-kib {v:?}"))?;
                if io_kib == 0 || (io_kib * 1024) % disk::SECTOR != 0 {
                    return Err(format!(
                        "--io-kib must be a non-zero multiple of {}",
                        disk::SECTOR / 1024
                    ));
                }
            }
            "--qd" => {
                let v = value(&mut i, "--qd")?;
                qd = v.parse().map_err(|_| format!("bad --qd {v:?}"))?;
                if qd == 0 {
                    return Err("--qd must be at least 1".into());
                }
            }
            "--emit" => {
                mode = Some(Mode::Emit { bytes: 0 });
                i += 1;
            }
            "--bytes" => {
                let v = value(&mut i, "--bytes")?;
                emit_bytes = Some(v.parse().map_err(|_| format!("bad --bytes {v:?}"))?);
            }
            "--panes" => {
                let v = value(&mut i, "--panes")?;
                panes = v.parse().map_err(|_| format!("bad --panes {v:?}"))?;
                if panes == 0 {
                    return Err("--panes must be at least 1".into());
                }
            }
            "--mib" => {
                let v = value(&mut i, "--mib")?;
                let n: u64 = v.parse().map_err(|_| format!("bad --mib {v:?}"))?;
                if n == 0 {
                    return Err("--mib must be at least 1".into());
                }
                mib = Some(n);
            }
            "--samples" => {
                let v = value(&mut i, "--samples")?;
                samples = v.parse().map_err(|_| format!("bad --samples {v:?}"))?;
                if samples == 0 {
                    return Err("--samples must be at least 1".into());
                }
            }
            "--gap-ms" => {
                let v = value(&mut i, "--gap-ms")?;
                gap_ms = v.parse().map_err(|_| format!("bad --gap-ms {v:?}"))?;
            }
            "--shell" => shell = Some(value(&mut i, "--shell")?),
            "--transport" => {
                let v = value(&mut i, "--transport")?;
                transport = match v.as_str() {
                    "pty" => Transport::Pty,
                    "pipe" => Transport::Pipe,
                    other => return Err(format!("bad --transport {other:?}, want pty or pipe")),
                };
            }
            "--no-attrib" => {
                attribution = false;
                i += 1;
            }
            other => return Err(format!("unexpected argument {other:?}")),
        }
    }

    let mode = match mode {
        Some(Mode::Emit { .. }) => Mode::Emit {
            bytes: emit_bytes.ok_or("--emit needs --bytes")?,
        },
        Some(m) => m,
        None => return Err(USAGE.to_string()),
    };
    // A drive needs a long stream to show its sustained rate; panes do not.
    let mib = mib.unwrap_or(match mode {
        Mode::Disk | Mode::Read => 2048,
        Mode::Compose => 256,
        Mode::Replay | Mode::CrashWriter => 8192,
        Mode::History => 16384,
        Mode::Parse => 64,
        _ => 32,
    });

    Ok(Args {
        mode,
        panes,
        mib,
        samples,
        gap: Duration::from_millis(gap_ms),
        shell,
        attribution,
        transport,
        path,
        io_kib,
        qd,
        threads,
        reps,
        noise_limit,
        conpty,
        emit_cached,
        emit_raw,
        echo,
        checkpoint_mib,
        kill_ms,
        visible,
        log,
        rate_mib,
        flush_mib,
        flush_path,
        render,
    })
}

/// Emit the synthetic workload to stdout, as a flooding pane does.
fn emit_workload(bytes: u64, cached: bool, raw: bool) -> io::Result<()> {
    const CHUNK: usize = 64 * 1024;
    let mut out: Box<dyn Write> = if raw {
        Box::new(raw_stdout()?)
    } else {
        Box::new(io::stdout().lock())
    };
    let mut written = 0u64;

    if cached {
        // Replay pre-generated bytes, so the emitter itself can never be the
        // bottleneck of what it measures.
        let mut source = Vec::with_capacity(4 * 1024 * 1024 + 512);
        emit::Generator::new(0xF01D_2A7E).fill(&mut source, 4 * 1024 * 1024);
        let mut at = 0usize;
        while written < bytes {
            let want = CHUNK.min((bytes - written) as usize);
            if at + want > source.len() {
                at = 0;
            }
            out.write_all(&source[at..at + want])?;
            at += want;
            written += want as u64;
        }
        return out.flush();
    }

    let mut generator = emit::Generator::new(0xF01D_2A7E);
    let mut buf = Vec::with_capacity(CHUNK + 512);
    while written < bytes {
        buf.clear();
        let want = CHUNK.min((bytes - written) as usize);
        generator.fill(&mut buf, want);
        out.write_all(&buf)?;
        written += buf.len() as u64;
    }
    out.flush()
}

/// Standard output as a plain file, bypassing `std`'s console path.
///
/// On Windows, when stdout is a console, `std::io::stdout` converts UTF-8 to
/// UTF-16 and calls `WriteConsoleW`. A cloned handle wrapped in a `File`
/// writes the same bytes with `WriteFile` instead — how a program that emits
/// VT bytes directly talks to a console host. No `unsafe`: the handle is
/// cloned into an owned one.
fn raw_stdout() -> io::Result<std::fs::File> {
    #[cfg(windows)]
    {
        use std::os::windows::io::AsHandle;
        Ok(std::fs::File::from(
            io::stdout().as_handle().try_clone_to_owned()?,
        ))
    }
    #[cfg(unix)]
    {
        use std::os::fd::AsFd;
        Ok(std::fs::File::from(
            io::stdout().as_fd().try_clone_to_owned()?,
        ))
    }
}

fn main() {
    let argv: Vec<String> = std::env::args().skip(1).collect();
    let args = match parse(&argv) {
        Ok(a) => a,
        Err(message) => {
            eprintln!("{message}");
            std::process::exit(2);
        }
    };

    if let Mode::Emit { bytes } = args.mode {
        if let Err(e) = emit_workload(bytes, args.emit_cached, args.emit_raw) {
            // A closed pipe is the normal way a pane ends early.
            if e.kind() != io::ErrorKind::BrokenPipe {
                eprintln!("fwbench: emit failed: {e}");
                std::process::exit(1);
            }
        }
        return;
    }

    #[cfg(windows)]
    if let Some(dll) = &args.conpty {
        if let Err(e) = pty::use_conpty_library(std::path::Path::new(dll)) {
            eprintln!("fwbench: cannot load ConPTY library {dll}: {e}");
            std::process::exit(1);
        }
        println!("console host: {dll} (not the system conhost.exe)");
    }

    // Every measuring mode is bracketed by the noisy-run guard.
    let before = resmon::sys::snapshot();
    let started = std::time::Instant::now();
    let code = run(&args);
    match (before, resmon::sys::snapshot()) {
        (Ok(prev), Ok(cur)) => {
            let n = noise::measure(
                &prev,
                &cur,
                std::process::id(),
                started.elapsed().as_secs_f64(),
                args.noise_limit,
            );
            print!("{}", noise::render(&n));
        }
        (Err(e), _) | (_, Err(e)) => println!(
            "
noise: not measured ({e})"
        ),
    }
    if code != 0 {
        std::process::exit(code);
    }
}

/// Run one measuring mode; returns the process exit code.
fn run(args: &Args) -> i32 {
    if args.mode == Mode::Disk {
        let dir = std::path::PathBuf::from(args.path.as_deref().unwrap_or("."));
        let bytes = args.mib * 1024 * 1024;
        let config = disk::Config {
            dir: dir.clone(),
            bytes,
            patterns: disk::Pattern::default_matrix(args.io_kib * 1024, args.qd),
        };
        eprintln!(
            "disk: {} MiB per pattern under {}...",
            args.mib,
            dir.display()
        );
        match disk::run(&config) {
            Ok(results) => print!("{}", disk::render(&dir, bytes, &results)),
            Err(e) => {
                eprintln!("fwbench: disk measurement failed: {e}");
                return 1;
            }
        }
        return 0;
    }

    if args.mode == Mode::Render {
        return run_render(args);
    }

    if args.mode == Mode::Glyphs {
        return run_glyphs(args);
    }

    if args.mode == Mode::History {
        let plan = history::Plan {
            dir: std::path::PathBuf::from(args.path.as_deref().unwrap_or(".")),
            bytes: args.mib * 1024 * 1024,
            jumps: args.samples,
            checkpoint_every: args.checkpoint_mib * 1024 * 1024,
        };
        eprintln!(
            "history: writing {} MiB under {}...",
            args.mib,
            plan.dir.display()
        );
        match history::run(&plan) {
            Ok(h) => print!("{}", history::render(&plan, &h)),
            Err(e) => {
                eprintln!("fwbench: history failed: {e}");
                return 1;
            }
        }
        return 0;
    }

    if args.mode == Mode::CrashWriter {
        let path = std::path::PathBuf::from(args.path.as_deref().unwrap_or("fwbench-crash.log"));
        // Killed mid-write by the parent; an error here is the parent's to see.
        let _ = replay::crash_writer(&path, args.mib * 1024 * 1024, args.io_kib * 1024);
        return 0;
    }

    if args.mode == Mode::Replay {
        let exe = match std::env::current_exe() {
            Ok(p) => p.to_string_lossy().into_owned(),
            Err(e) => {
                eprintln!("fwbench: cannot find own path: {e}");
                return 1;
            }
        };
        let dir = std::path::PathBuf::from(args.path.as_deref().unwrap_or("."));
        let config = replay::Config {
            dir: dir.clone(),
            bytes: args.mib * 1024 * 1024,
            io: args.io_kib * 1024,
            run_for: Duration::from_millis(args.kill_ms),
            rebuild_bytes: 3 * 1024 * 1024 + 300 * 1024, // the 3.3 MiB of 8.0
        };
        eprintln!(
            "replay: writing under {} for {} ms, then killing the writer...",
            dir.display(),
            args.kill_ms
        );
        match replay::run(&exe, &config) {
            Ok(r) => print!("{}", replay::render(&config, &r)),
            Err(e) => {
                eprintln!("fwbench: replay failed: {e}");
                return 1;
            }
        }
        return 0;
    }

    if args.mode == Mode::Compose {
        let dir = std::path::PathBuf::from(args.path.as_deref().unwrap_or("."));
        let config = compose::Config {
            panes: args.panes,
            visible: args.visible.min(args.panes),
            bytes_per_pane: args.mib * 1024 * 1024,
            log: args.log,
            dir: dir.clone(),
            io: args.io_kib * 1024,
            rate_mib: args.rate_mib,
            stop: None,
        };
        eprintln!(
            "compose: {} panes x {} MiB, {} visible, log {} under {}...",
            config.panes,
            args.mib,
            config.visible,
            config.log.name(),
            dir.display()
        );
        if !args.echo {
            match compose::run(&config) {
                Ok(result) => print!("{}", compose::render(&config, &result)),
                Err(e) => {
                    eprintln!("fwbench: compose failed: {e}");
                    return 1;
                }
            }
            return 0;
        }
        return compose_with_echo(args, config);
    }

    if args.mode == Mode::Read {
        let dir = std::path::PathBuf::from(args.path.as_deref().unwrap_or("."));
        let config = read::Config {
            dir: dir.clone(),
            bytes: args.mib * 1024 * 1024,
            io: args.io_kib * 1024,
            flush_bytes: args.flush_mib * 1024 * 1024,
            flush_dir: args.flush_path.as_deref().map(std::path::PathBuf::from),
        };
        eprintln!(
            "read: writing a {} MiB probe under {}...",
            args.mib,
            dir.display()
        );
        match read::run(&config) {
            Ok(report) => print!("{}", read::render(&report)),
            Err(e) => {
                eprintln!("fwbench: read measurement failed: {e}");
                return 1;
            }
        }
        return 0;
    }

    if args.mode == Mode::Gpu {
        eprintln!(
            "gpu: warming up 2 s, then {} copies per cell...",
            args.samples
        );
        match gpu::run(args.samples, Duration::from_secs(2)) {
            Ok((label, cells)) => print!("{}", gpu::render(&label, &cells)),
            Err(e) => {
                eprintln!("fwbench: gpu measurement failed: {e}");
                return 1;
            }
        }
        return 0;
    }

    if args.mode == Mode::Parse {
        let bytes = (args.mib * 1024 * 1024) as usize;
        let cfg = e4::Config {
            bytes,
            reps: args.reps,
            threads: args.threads.clone(),
            offsets: 10_000,
        };
        eprintln!("parse: generating {} MiB workload...", args.mib);
        let data = e4::workload(0, bytes);
        eprintln!("parse: split ({} reps)...", cfg.reps);
        let split = e4::split(&data, cfg.reps);
        let mut scaling = Vec::new();
        for &t in &cfg.threads {
            eprintln!("parse: scaling, {t} thread(s)...");
            scaling.push((t, e4::scaling(t, bytes, cfg.reps)));
        }
        eprintln!("parse: convergence over {} boundaries...", cfg.offsets);
        let conv = e4::convergence(&data, cfg.offsets, e4::FEED);
        print!("{}", e4::render(&cfg, &split, &scaling, &conv));
        return 0;
    }

    let exe = match std::env::current_exe() {
        Ok(p) => p.to_string_lossy().into_owned(),
        Err(e) => {
            eprintln!("fwbench: cannot find own path: {e}");
            return 1;
        }
    };
    let shell = args
        .shell
        .clone()
        .unwrap_or_else(|| echo::default_shell().to_string());
    let bytes_per_pane = args.mib * 1024 * 1024;

    let before = if args.attribution {
        resmon::sys::snapshot().ok()
    } else {
        None
    };
    let started = std::time::Instant::now();

    let run = match args.mode {
        Mode::Emit { .. }
        | Mode::Disk
        | Mode::Parse
        | Mode::Gpu
        | Mode::Read
        | Mode::Compose
        | Mode::Replay
        | Mode::CrashWriter
        | Mode::History
        | Mode::Render
        | Mode::Glyphs => {
            unreachable!("handled above")
        }
        Mode::Flood => {
            eprintln!("flooding {} panes x {} MiB...", args.panes, args.mib);
            Run {
                flood: Some(flood::run(
                    &exe,
                    args.panes,
                    bytes_per_pane,
                    24,
                    80,
                    args.transport,
                    &emit_flags(args),
                )),
                echo: None,
                attribution: None,
            }
        }
        Mode::Echo => {
            eprintln!("measuring {} key echoes through `{shell}`...", args.samples);
            Run {
                flood: None,
                echo: measure_echo(&shell, args.samples, args.gap),
                attribution: None,
            }
        }
        Mode::Combined => {
            eprintln!(
                "flooding {} panes x {} MiB while measuring {} key echoes through `{shell}`...",
                args.panes, args.mib, args.samples
            );
            let exe_for_flood = exe.clone();
            let emit = emit_flags(args);
            let panes = args.panes;
            let transport = args.transport;
            let flooder = std::thread::spawn(move || {
                flood::run(
                    &exe_for_flood,
                    panes,
                    bytes_per_pane,
                    24,
                    80,
                    transport,
                    &emit,
                )
            });
            let echo = measure_echo(&shell, args.samples, args.gap);
            let flood = flooder.join().ok();
            Run {
                flood,
                echo,
                attribution: None,
            }
        }
    };

    let attribution = match before {
        Some(before) => resmon::sys::snapshot()
            .ok()
            .map(|after| resmon::attribute(&before, &after, started.elapsed().as_secs_f64())),
        None => None,
    };
    let run = Run { attribution, ..run };

    print!("{}", report::render(&run));
    println!("verdict: {}", report::verdict(&run));
    0
}

/// The emitter flags a flood passes to each pane.
fn emit_flags(args: &Args) -> Vec<String> {
    let mut v = Vec::new();
    if args.emit_cached {
        v.push("--cached".to_string());
    }
    if args.emit_raw {
        v.push("--raw".to_string());
    }
    v
}

/// Key echo measured idle, then again while the composed pipeline runs: the
/// section 4 input target is stated *over the shell's own latency*, so the
/// idle run is the baseline the loaded one is judged against.
fn compose_with_echo(args: &Args, mut config: compose::Config) -> i32 {
    let shell = args
        .shell
        .clone()
        .unwrap_or_else(|| echo::default_shell().to_string());

    eprintln!(
        "echo: baseline, {} keys through `{shell}`, idle...",
        args.samples
    );
    let Some(idle) = measure_echo(&shell, args.samples, args.gap) else {
        return 1;
    };

    let stop = std::sync::Arc::new(std::sync::atomic::AtomicBool::new(false));
    config.stop = Some(stop.clone());
    eprintln!("echo: same keys while the pipeline runs...");
    let (composed, loaded) = std::thread::scope(|s| {
        let load = s.spawn(|| compose::run(&config));
        // Let every pane reach steady state before the first key.
        std::thread::sleep(Duration::from_millis(500));
        let loaded = measure_echo(&shell, args.samples, args.gap);
        stop.store(true, std::sync::atomic::Ordering::Relaxed);
        (load.join().expect("compose thread"), loaded)
    });

    let composed = match composed {
        Ok(c) => c,
        Err(e) => {
            eprintln!("fwbench: compose failed: {e}");
            return 1;
        }
    };
    let Some(loaded) = loaded else {
        return 1;
    };
    if composed.wall < loaded.samples.iter().sum::<Duration>() {
        eprintln!("fwbench: warning: the load ended before the echo run did");
    }

    print!("{}", compose::render(&config, &composed));
    print!("{}", render_echo_pair(&idle, &loaded));
    0
}

/// Idle and loaded echo side by side, judged against the section 4 target:
/// p50 < 1 ms and p99 < 5 ms *over* the shell's own latency.
fn render_echo_pair(idle: &echo::EchoResult, loaded: &echo::EchoResult) -> String {
    let ms = |d: Duration| d.as_secs_f64() * 1000.0;
    let over50 = ms(loaded.summary.p50) - ms(idle.summary.p50);
    let over99 = ms(loaded.summary.p99) - ms(idle.summary.p99);
    let verdict = |over: f64, limit: f64| {
        if over < limit {
            "meets"
        } else {
            "MISSES"
        }
    };
    format!(
        "\nkey echo through `{}`, {:.0} ms between keys\n\n\
         | | p50 | p90 | p99 | lost |\n| --- | --- | --- | --- | --- |\n\
         | idle | {:.2} ms | {:.2} ms | {:.2} ms | {} |\n\
         | under the pipeline | {:.2} ms | {:.2} ms | {:.2} ms | {} |\n\
         | added by the load | {:+.2} ms ({} p50 < 1 ms) | | {:+.2} ms ({} p99 < 5 ms) | |\n",
        loaded.shell,
        ms(loaded.gap),
        ms(idle.summary.p50),
        ms(idle.summary.p90),
        ms(idle.summary.p99),
        idle.lost,
        ms(loaded.summary.p50),
        ms(loaded.summary.p90),
        ms(loaded.summary.p99),
        loaded.lost,
        over50,
        verdict(over50, 1.0),
        over99,
        verdict(over99, 5.0),
    )
}

fn measure_echo(shell: &str, samples: usize, gap: Duration) -> Option<echo::EchoResult> {
    match echo::run(shell, samples, gap) {
        Ok(r) => Some(r),
        Err(e) => {
            eprintln!("fwbench: echo measurement failed: {e}");
            None
        }
    }
}

